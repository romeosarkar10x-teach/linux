#!/usr/bin/env bash
# setup.sh -- seeds /labs/08-streams-and-redirection/03-heredocs
#
# THE ANSWER KEY. Students are told not to open this.
#
# Teaching goal: a here-document is a redirection of fd 0 from text the shell
# holds, not from a file. Two decisions matter and both bite:
#   1. QUOTED vs UNQUOTED delimiter. <<EOF expands $var, `cmd`, \ escapes.
#      <<'EOF' does not. Every "why did my script eat the dollar signs" bug is
#      this one decision.
#   2. <<- strips LEADING TABS ONLY. Not spaces. This is the single most
#      commonly misremembered fact in the shell, so the lab ships one file
#      indented with tabs and one with spaces and lets the student measure.
#
# Also here: <<< herestrings, and the fact that a heredoc is stdin, so it
# composes with everything that reads stdin.
#
# THE BROKEN SCRIPT: bin/mkbanner uses an unquoted delimiter and its output is
# missing the literal $ fields. bin/mkbanner-fixed is the same script with one
# character changed. Exercise 28 asks which character.
#
# Measured facts used by the exercises:
#   templates/banner.txt     4 lines, contains $DECK $SHIFT literally
#   templates/tabbed.txt     4 lines, indented with TABS
#   templates/spaced.txt     4 lines, indented with SPACES (identical text)
#   data/decks.txt           4 lines
#
# Idempotent: removes its own tree first, creates nothing outside LAB.
