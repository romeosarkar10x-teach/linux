cat > notes/heredoc.txt <<'OUTER'
Here-documents
--------------

A here-document is a redirection of fd 0. The text does not live in a file --
the shell holds it and hands it to the command as standard input.

  cmd <<EOF
  ...lines...
  EOF

The delimiter is any word you like. EOF is a convention, not a keyword. The
closing line must contain the delimiter and nothing else, at the start of the
line, with no trailing spaces. A trailing space is the classic cause of
"unexpected end of file".

THE ONE DECISION THAT MATTERS

  <<EOF     the body is expanded: $var, ${var}, $(cmd), `cmd`, \ escapes
  <<'EOF'   the body is literal: every character survives, nothing runs
  <<"EOF"   same as quoted. Any quoting of the delimiter turns expansion off.

Quote the delimiter unless you actually want expansion. A body that contains
shell syntax -- a script, a config file, an awk program, a password, anything
with a $ in it -- must be quoted or the shell will help you.

INDENTATION

  <<-EOF    strips leading TABS from every body line and from the delimiter

TABS ONLY. Not spaces. An editor set to "insert spaces" makes <<- do nothing
at all, silently, and the body keeps its indentation. This is why so many
scripts have a heredoc jammed against the left margin in the middle of an
indented block: somebody gave up.

HERESTRINGS

  cmd <<<"one line of text"

Same idea, one line, and the same quoting rules. `<<<` adds a trailing
newline. It is the shortest way to feed a string to something that insists on
reading stdin:

  grep -c deck <<<"$text"
  read -r a b <<<"05 beta"

WHAT A HEREDOC IS NOT

It is not a string literal and it is not a file. It is fd 0. So it composes:
anything that reads stdin can be fed one, including things you would not think
of -- `wc`, `sort`, `sed`, `bash` itself.
OUTER

