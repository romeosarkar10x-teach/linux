#!/usr/bin/env bash
# Checkpoint 1. Usage: compare-view <section-directory-name>
#
# Name the archive section that one account cannot see and everyone else can.
set -uo pipefail

LAB="/labs/11-environment-and-config/06-incident-10"
want="02-navigation"

if [ $# -ne 1 ]; then
    echo "compare-view: give me exactly one section name." >&2
    echo "usage: compare-view <section-directory-name>" >&2
    exit 2
fi

if [ ! -d "$LAB/archive/$1" ]; then
    echo "REJECTED: '$1' is not a section of this archive." >&2
    echo "          There are five. Two shells disagree about how many." >&2
    exit 1
