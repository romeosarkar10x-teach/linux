    echo "REJECTED: '$1' is visible in both shells. Compare them again." >&2
    echo "          Run the same command in your shell and in a login shell" >&2
    echo "          with HOME set to the account, and diff the two lists." >&2
    exit 1
fi

echo "STAGE{one-directory-two-answers}"
EOF
