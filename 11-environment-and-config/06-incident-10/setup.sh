#!/usr/bin/env bash
# Seeds 11/06 -- Incident 10. Trace 11.
#
# The trace: a line in a startup file, sourced three levels down, that removes
# exactly one directory from one account's view of the station archive. The
# file it hides is the chapter 2 archive. Nothing is deleted, nothing is
# chmodded, nothing is renamed. The directory is there for everyone whose shell
# has not been taught not to see it.
#
# Mechanism (measured before writing):
#   GLOBIGNORE with a pattern makes matching names vanish from ALL globbing --
#     echo */, ls *, tab completion -- and it also silently switches dotglob on
#   an `alias ls='ls --hide=...'` hides it from a bare `ls` as well, so the two
#     mechanisms cover each other and finding one is not finding both
#   both live in ~/.config/kestrel/env.sh, sourced by .bashrc, sourced by
#     .profile -- so `grep GLOBIGNORE ~/.bashrc` finds nothing
#   `find`, `echo` with a quoted name, and `ls -d name` all still see it: the
#     directory is not hidden, the shell is
#
# Four stages. Stage tokens are STAGE{...} and are NOT registered as flags.
set -euo pipefail

LAB="/labs/11-environment-and-config/06-incident-10"

