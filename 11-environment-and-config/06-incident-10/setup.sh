# --- stage 2: name the mechanism and the file it lives in -------------------
cat > "$LAB/bin/name-mechanism" <<'EOF'
#!/usr/bin/env bash
# Checkpoint 2. Usage: name-mechanism <VARIABLE> <path-to-file>
#
# Two things hide that directory and they are not the same thing. Name the
# shell VARIABLE that hides it from globbing, and the file both of them live
# in, as a path relative to the account's home directory.
set -uo pipefail

if [ $# -ne 2 ]; then
    echo "name-mechanism: two arguments." >&2
    echo "usage: name-mechanism <VARIABLE> <path-relative-to-home>" >&2
    exit 2
fi

var=$1
file=${2#./}
file=${file#\~/}

case "$var" in
    GLOBIGNORE) ;;
    LS_COLORS|GLOBIGNORECASE|HIDE|IGNOREEOF|FIGNORE)
        echo "REJECTED: '$var' is a real variable and it is not this one." >&2
        echo "          The one you want removes names from a glob's result." >&2
        exit 1 ;;
    *)
        echo "REJECTED: '$var' is not what is hiding it from '*'." >&2
        echo "          A shell variable is doing it. Read the account's" >&2
        echo "          startup files all the way down -- .profile sources" >&2
        echo "          something, which sources something else." >&2
        exit 1 ;;
esac

case "$file" in
    .config/kestrel/env.sh) ;;
    .bashrc|.profile|.bash_profile)
        echo "REJECTED: the account does read '$file', but the line is not in" >&2
        echo "          it. Follow what that file sources." >&2
        exit 1 ;;
    *)
        echo "REJECTED: '$file' is not where it is written." >&2
        exit 1 ;;
esac

echo "STAGE{two-mechanisms-one-file}"
EOF
chmod 755 "$LAB/bin/name-mechanism"

# --- stage 3: repair, without touching the generated file -------------------
cat > "$LAB/bin/verify-repair" <<'EOF'
#!/usr/bin/env bash
# Checkpoint 3. Usage: verify-repair
#
# Checks three things:
#   1. .config/kestrel/env.sh is byte-for-byte what the toolchain generated
#   2. a fresh LOGIN shell for that account sees all five archive sections
#      when it globs
#   3. that same shell's `ls` shows all five too
set -uo pipefail

LAB="/labs/11-environment-and-config/06-incident-10"
HOMEDIR="$LAB/homes/dorn"
GENERATED="423edca9f8d10d158b52dbb51727c871"

fail() { echo "REJECTED: $*" >&2; exit 1; }

[ -f "$HOMEDIR/.config/kestrel/env.sh" ] \
    || fail "the generated file is gone. That is not a repair. kestrel reset 11/06"

got=$(md5sum < "$HOMEDIR/.config/kestrel/env.sh" | cut -d' ' -f1)
[ "$got" = "$GENERATED" ] \
    || fail "the generated file has been edited. Put it back (kestrel reset 11/06 if you must) and fix this somewhere the toolchain will not overwrite."

glob=$(printf '%s\n' 'cd "$ARCHIVE" || exit 1' 'echo */' \
       | env -i HOME="$HOMEDIR" PATH=/usr/local/bin:/usr/bin:/bin TERM=dumb bash -l 2>/dev/null)
case "$glob" in
    *02-navigation*) ;;
    "") fail "a fresh login shell for that account could not even reach the archive. Did ARCHIVE survive your edit?" ;;
    *)  fail "a fresh login shell still cannot glob 02-navigation. It saw: $glob" ;;
esac

# The alias must be expanded on a LATER line than the shopt -- 11/04's rule.
lsout=$(printf '%s\n' 'shopt -s expand_aliases' 'cd "$ARCHIVE" || exit 1' 'ls' \
        | env -i HOME="$HOMEDIR" PATH=/usr/local/bin:/usr/bin:/bin TERM=dumb bash -l 2>/dev/null)
case "$lsout" in
    *02-navigation*) ;;
    *) fail "globbing is fixed but a bare \`ls\` still hides it. There were two mechanisms. You have dealt with one." ;;
esac

echo "STAGE{last-line-wins}"
echo
echo "Repair verified. The generated file is untouched and the account sees"
echo "the whole archive. Checkpoint 4: bin/incident-close"
EOF
chmod 755 "$LAB/bin/verify-repair"

